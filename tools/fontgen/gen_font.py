"""Generates src/frontend/font_data.inc: DejaVu Sans glyphs for printable
ASCII as 8-bit coverage bitmaps, for the front end's menus.

    python3 tools/fontgen/gen_font.py /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf

DejaVu fonts are free to embed (Bitstream Vera / DejaVu license).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZE, HEIGHT = 12, 16
font = ImageFont.truetype(sys.argv[1], SIZE)
ascent, _ = font.getmetrics()
glyphs = []
for code in range(32, 127):
    ch = chr(code)
    advance = max(1, round(font.getlength(ch)))
    img = Image.new('L', (advance + 2, HEIGHT), 0)
    ImageDraw.Draw(img).text((0, HEIGHT - 3 - ascent), ch, font=font, fill=255)
    glyphs.append((code, advance, img))

out = ['// Generated by tools/fontgen/gen_font.py from DejaVu Sans Bold %dpx; do not edit.' % SIZE,
       'constexpr int kFontHeight = %d;' % HEIGHT,
       'struct FontGlyph { int advance, width, offset; };',
       'constexpr FontGlyph kFontGlyphs[95] = {']
data, offset = [], 0
for code, advance, img in glyphs:
    w = img.width
    out.append('    {%d, %d, %d},  // %r' % (advance, w, offset, chr(code)))
    data.extend(img.tobytes())
    offset += w * HEIGHT
out.append('};')
out.append('constexpr unsigned char kFontCoverage[%d] = {' % len(data))
for i in range(0, len(data), 24):
    out.append('    ' + ', '.join(str(v) for v in data[i:i + 24]) + ',')
out.append('};')
open(sys.argv[2] if len(sys.argv) > 2 else 'src/frontend/font_data.inc', 'w').write('\n'.join(out) + '\n')
